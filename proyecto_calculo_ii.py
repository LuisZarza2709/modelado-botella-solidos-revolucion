"""#Método de la Arandela


**Teorema del Volumen por el Método de la Arandela**

Hipótesis: Sean $f, g : [a,b] \to \mathbb{R}$ funciones continuas, no negativas, tales que $f(x) \geq g(x)$ para todo $x \in [a,b]$.

Construcción: La región limitada por las gráficas de $f$ y $g$, y las rectas $x = a$ y $x = b$, se gira alrededor del eje $X$, generando un \textit{sólido de revolución hueco}.

Aproximación: Se subdivide $[a,b]$ en $n$ subintervalos. En cada subintervalo $[x_{i-1}, x_i]$ se forma una arandela de radios exterior $f(x)$ e interior $g(x)$, y ancho $h_i = x_i - x_{i-1}$.


**Aproximación inferior (arandelas inscritas):**

$V_{\text{inf}} = \sum_{i=1}^n \pi \left( m_i^2(f) - M_i^2(g) \right) h_i$

\textbf{Aproximación superior (arandelas circunscritas):}

$V_{\text{sup}} = \sum_{i=1}^n \pi \left( M_i^2(f) - m_i^2(g) \right) h_i$



Paso al límite: Como f y g son continuas, $f^2$ y $g^2$ son integrables. Entonces, al refinar la partición ($n \to \infty$), obtenemos:

V = $\lim_{n \to \infty} \sum_{i=1}^n \pi \left( f(c_i)^2 - g(c_i)^2 \right) h_i = \pi \int_a^b \left( f(x)^2 - g(x)^2 \right)$ dx

Conclusión: El volumen del sólido de revolución es:

V = $\pi \int_a^b \left( f(x)^2 - g(x)^2 \right)$ dx


"""

